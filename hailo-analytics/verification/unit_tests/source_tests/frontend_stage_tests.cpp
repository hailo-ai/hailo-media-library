// ============================================================================
// Buffer Forwarding Tests
// ============================================================================
// These tests verify that buffers actually flow from the frontend through the
// FrontendStage to subscribers. They start the real pipeline and wait for
// actual buffers to be produced by the frontend's input source.
// ============================================================================

TEST_F(FrontendStageTest, BuffersForwardedToSubscriber)
{
    auto stage = std::make_shared<FrontendStage>("test_frontend");
    stage->configure(get_frontend());

    // Get first available stream ID from configuration
    auto streams = stage->get_outputs_streams();
    ASSERT_TRUE(streams.has_value() && !streams.value().empty());
    auto stream_id = streams.value()[0].id;

    // Use TestThreadedStage which can accept buffers in its own thread
    auto subscriber = std::make_shared<TestThreadedStage>("subscriber_1", 10);
    stage->subscribe_to_stream(stream_id, subscriber);

    // Start the stage (which starts the frontend and begins producing buffers)
    stage->start();
    subscriber->start();

    // Wait for the frontend to produce and forward some buffers
    // The frontend will autonomously produce buffers from its input source
    std::this_thread::sleep_for(std::chrono::seconds(2));

    // Stop stages
    stage->stop();
    subscriber->stop();

    // Verify that buffers were received
    // We don't check exact count since it depends on framerate and timing,
    // just that some buffers flowed through
    auto processed = subscriber->get_process_call_count();
    EXPECT_GT(processed, 0) << "Subscriber should have received buffers from frontend";
}

