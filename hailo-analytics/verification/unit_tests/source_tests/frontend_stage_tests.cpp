// Test thread safety with multiple subscribers receiving buffers concurrently
TEST_F(FrontendStageTest, ThreadSafetyWithMultipleConcurrentSubscribers)
{
    auto stage = std::make_shared<FrontendStage>("test_frontend");
    stage->configure(get_frontend());

    auto streams = stage->get_outputs_streams();
    ASSERT_TRUE(streams.has_value() && !streams.value().empty());
    auto stream_id = streams.value()[0].id;

    // Create multiple subscribers that will all receive buffers concurrently
    std::vector<std::shared_ptr<TestThreadedStage>> subscribers;
    const int num_subscribers = 5;

    for (int i = 0; i < num_subscribers; i++)
    {
        auto sub = std::make_shared<TestThreadedStage>("subscriber_" + std::to_string(i), 10);
        subscribers.push_back(sub);
        stage->subscribe_to_stream(stream_id, sub);
    }

    // Start all subscribers and the stage
    stage->start();
    for (auto &sub : subscribers)
    {
        sub->start();
    }

    // Let buffers flow to all subscribers concurrently
    std::this_thread::sleep_for(std::chrono::seconds(2));

    // Stop all
    stage->stop();
    for (auto &sub : subscribers)
    {
        sub->stop();
    }

    // Verify all subscribers received buffers safely without crashes
    for (size_t i = 0; i < subscribers.size(); i++)
    {
        auto processed = subscribers[i]->get_process_call_count();
        EXPECT_GT(processed, 0) << "Subscriber " << i << " should have received buffers";
    }
}

