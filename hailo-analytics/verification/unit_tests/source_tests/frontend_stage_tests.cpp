// ============================================================================
// Test Helper - Creates MediaLibrary with Frontend for testing
// ============================================================================

// Helper to create a MediaLibrary instance with a valid frontend configuration.
// This uses the full MediaLibrary initialization to properly set up the frontend.
//
// BUFFER FLOW TESTING APPROACH:
// ==============================
// Unlike typical unit tests that mock dependencies, these tests use REAL buffer flow
// from the MediaLibraryFrontend because:
//
// 1. The frontend produces buffers autonomously from its GStreamer pipeline
// 2. Buffers are generated by the configured input source at a steady FPS
// 3. There's no external API to "inject" or "simulate" buffers
// 4. The callback mechanism is internal to GStreamer elements
//
// Therefore, to test buffer forwarding:
// - We use the real MediaLibrary with actual configuration files
// - We start the pipeline (which activates the input source)
// - We wait for real buffers to be produced and flow through
// - We use TestThreadedStage subscribers (which process buffers in their own threads)
// - We verify that buffers were received (without checking exact counts)
//
// This makes these tests more integration-style, but it's the only way to properly
// test the FrontendStage's buffer forwarding functionality with the real frontend.
class MediaLibraryTestHelper
{
  public:
    MediaLibraryPtr media_lib;
    std::atomic<int> subscribe_call_count{0};
    std::atomic<int> start_call_count{0};
    std::atomic<int> stop_call_count{0};
    FrontendCallbacksMap stored_callbacks;
    std::mutex callbacks_mutex;

    // Create a MediaLibrary instance with frontend configured
    // Uses the test configuration from the examples directory
    static std::shared_ptr<MediaLibraryTestHelper> create()
    {
        auto helper = std::make_shared<MediaLibraryTestHelper>();

        // Create MediaLibrary
        auto media_lib_result = MediaLibrary::create();
        if (!media_lib_result.has_value())
        {
            throw std::runtime_error("Failed to create MediaLibrary for testing");
        }

        helper->media_lib = media_lib_result.value();

        // Try to load configuration from examples directory
        // If not available, skip the test
        std::ifstream config_file(config_path);
        if (!config_file.good())
        {
            throw std::runtime_error("Frontend test configuration file not found (" + config_path +
                                     "). Tests require media library configuration.");
        }

        std::string config_string((std::istreambuf_iterator<char>(config_file)), std::istreambuf_iterator<char>());
        config_file.close();

        // Initialize the media library with the configuration
        auto init_status = helper->media_lib->initialize(config_string);
        if (init_status != MEDIA_LIBRARY_SUCCESS)
        {
            throw std::runtime_error("Failed to initialize MediaLibrary with configuration");
        }

        return helper;
    }

    MediaLibraryFrontendPtr get_frontend()
    {
        return media_lib->m_frontend;
    }

    // Track subscribe calls by wrapping the frontend's subscribe method
    media_library_return subscribe_to_frontend(FrontendCallbacksMap callbacks)
    {
        subscribe_call_count++;
        {
            std::lock_guard<std::mutex> lock(callbacks_mutex);
            stored_callbacks = callbacks;
        }
        return media_lib->subscribe_to_frontend_output(callbacks);
    }

    // Track start/stop through the media library
    media_library_return start_pipeline()
    {
        start_call_count++;
        return media_lib->start_pipeline();
    }

    media_library_return stop_pipeline()
    {
        stop_call_count++;
        return media_lib->stop_pipeline();
    }

    ~MediaLibraryTestHelper()
    {
        if (media_lib)
        {
            media_lib->stop_pipeline();
        }
    }
};
