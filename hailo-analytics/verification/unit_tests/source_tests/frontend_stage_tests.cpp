// Test that stage can be stopped and restarted
TEST_F(FrontendStageTest, StageCanBeStoppedAndRestarted)
{
    auto stage = std::make_shared<FrontendStage>("test_frontend");
    stage->configure(get_frontend());

    auto streams = stage->get_outputs_streams();
    ASSERT_TRUE(streams.has_value() && !streams.value().empty());
    auto stream_id = streams.value()[0].id;

    auto subscriber = std::make_shared<TestThreadedStage>("subscriber_1", 10);
    stage->subscribe_to_stream(stream_id, subscriber);

    // First run
    subscriber->start();
    stage->start();
    std::this_thread::sleep_for(std::chrono::seconds(1));
    stage->stop();
    subscriber->stop();
    std::this_thread::sleep_for(std::chrono::seconds(1));

    auto first_count = subscriber->get_process_call_count();
    EXPECT_GT(first_count, 0) << "Should receive buffers in first run";

    // Second run - restart the same stage
    subscriber->start();
    stage->start();
    std::this_thread::sleep_for(std::chrono::seconds(1));
    stage->stop();
    subscriber->stop();
    std::this_thread::sleep_for(std::chrono::seconds(1));

    auto second_count = subscriber->get_process_call_count();
    EXPECT_GT(second_count, first_count) << "Should receive more buffers after restart";
}

