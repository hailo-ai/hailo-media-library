// FrontendStage Test Fixture
// ============================================================================

class FrontendStageTest : public ::testing::Test
{
  protected:
    std::shared_ptr<MediaLibraryTestHelper> media_lib_helper;
    HailoMediaLibraryBufferPtr mock_buffer;

    void SetUp() override
    {
        try
        {
            media_lib_helper = MediaLibraryTestHelper::create();
            mock_buffer = std::make_shared<hailo_media_library_buffer>();
        }
        catch (const std::exception &e)
        {
            GTEST_SKIP() << "Failed to create MediaLibrary for frontend testing: " << e.what()
                         << "\nNote: FrontendStage tests require valid media library configuration files.";
        }
    }

    void TearDown() override
    {
        if (media_lib_helper)
        {
            media_lib_helper->stop_pipeline();
        }
        media_lib_helper.reset();
        mock_buffer.reset();
    }

    BufferPtr create_test_buffer()
    {
        return std::make_shared<Buffer>(mock_buffer);
    }

    MediaLibraryFrontendPtr get_frontend()
    {
        return media_lib_helper->get_frontend();
    }
};

